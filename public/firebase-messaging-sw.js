// RailBook does not use Firebase. Browsers that previously ran another app on
// this origin keep requesting this service worker; this version removes itself
// so those requests stop.
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => {
  event.waitUntil(
    self.registration
      .unregister()
      .then(() => self.clients.matchAll({ type: "window" }))
      .then((clients) => clients.forEach((client) => client.navigate(client.url))),
  );
});
